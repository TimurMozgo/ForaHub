import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createHmac} from 'node:crypto';
import ts from 'typescript';
const source=readFileSync(new URL('../lib/support-payments.ts',import.meta.url),'utf8');
const code=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText;
const m=await import(`data:text/javascript;base64,${Buffer.from(code).toString('base64')}`);
const token='test-only', now=Date.now(),user=12345;
const data=new URLSearchParams({auth_date:String(Math.floor(now/1000)),user:JSON.stringify({id:user})});
const check=[...data].sort(([a],[b])=>a.localeCompare(b)).map(([k,v])=>`${k}=${v}`).join('\n');
const secret=createHmac('sha256','WebAppData').update(token).digest();
data.set('hash',createHmac('sha256',secret).update(check).digest('hex'));
assert.equal(m.telegramUser(data.toString(),token,now),user);
assert.equal(m.telegramUser(data.toString(),token,now+7200000),null);
assert.equal(m.telegramUser(data.toString(),token+'wrong',now),null);
assert.equal(m.telegramUser(data.toString()+'&user={}',token,now),null);
const payload=m.makePayload(user,50,token,now);
assert(m.validPayload(payload,user,50,token,now));
assert(!m.validPayload(payload,user,500,token,now));
assert(!m.validPayload(payload,user+1,50,token,now));
assert(!m.validPayload(payload,user,50,token,now+7200000));
for(const value of [0,-1,1.5,'50',NaN,100001])assert(!m.validAmount(value));
const request=new Request('https://example.com/api/support/invoice',{method:'POST',body:JSON.stringify({amount:50,initData:data.toString()})});
assert.equal((await m.supportInvoice(request,{})).status,503);
const env={FORAHUB_SUPPORT_ENABLED:'true',FORAHUB_BOT_TOKEN:token,FORAHUB_WEBHOOK_SECRET:'webhook-test'};
const calls=[];
globalThis.fetch=async(url,options)=>{calls.push({url,body:JSON.parse(options.body)});return Response.json({ok:true,result:'https://t.me/$test'});};
assert.equal((await m.supportInvoice(request,env)).status,200);
assert.equal(calls[0].body.currency,'XTR');assert.equal(calls[0].body.prices[0].amount,50);
assert.equal((await m.supportWebhook(new Request('https://example.com',{method:'POST'}),env)).status,401);
const webhook=q=>new Request('https://example.com',{method:'POST',headers:{'X-Telegram-Bot-Api-Secret-Token':'webhook-test'},body:JSON.stringify({pre_checkout_query:q})});
const query={id:'q1',from:{id:user},currency:'XTR',total_amount:50,invoice_payload:payload};
assert.equal((await m.supportWebhook(webhook(query),env)).status,200);assert.equal(calls.at(-1).body.ok,true);
await m.supportWebhook(webhook({...query,total_amount:500}),env);assert.equal(calls.at(-1).body.ok,false);
console.log('Support checks passed: auth, expiry, tampering, amount, disabled gate, invoice, pre-checkout.');
